"""Build the star schema from the data lake and load it into Postgres.

    python -m harbor_haze.warehouse.build --lake data/lake              # load into Postgres
    python -m harbor_haze.warehouse.build --lake data/lake --dry-run out/  # write CSVs only

The transforms (build_*) are pure pandas and take plain DataFrames, so they can be tested
without Parquet or Postgres. Only read_table() and load_postgres() touch the outside world.

Grain of the fact table: one row per site x pollutant x UTC hour. Collocated instruments
(several POCs at one site) are averaged and counted in n_poc.
"""

from __future__ import annotations

import argparse
import io
import os
from pathlib import Path

import numpy as np
import pandas as pd

RADIUS_KM = 10.0  # vessel cells within this distance of a monitor count as "near" it
CELL_DEG = 0.02  # lake grid cell size; cell_lat/cell_lon are the south-west corner
LOCAL_TZ = "America/Los_Angeles"

# parameter_key, label. "wind" in raw/epa_hourly is deliberately not a pollutant.
PARAMS = {
    "pm25": (1, "PM2.5 reference (88101)"),
    "pm25_nonref": (2, "PM2.5 non-reference (88502)"),
    "no2": (3, "NO2 (42602)"),
}

# GHCN-Hourly station ids are matched by substring, then each monitor uses the nearer one.
# CHECK against the `station=` folder names in data/lake/raw/ghcnh; the loader fails loudly
# and prints the values it saw if nothing matches.
WX_STATIONS = {
    "LGB": {"tokens": ["lgb", "23129"], "lat": 33.8177, "lon": -118.1516},
    "LAX": {"tokens": ["lax", "23174"], "lat": 33.9425, "lon": -118.4081},
}

COUNT_COLS = [
    "n_pings",
    "n_vessels",
    "n_stationary",
    "n_underway",
    "n_cargo",
    "n_tanker",
    "n_passenger",
    "n_tug",
    "n_cargo_tanker",
    "n_cargo_tanker_stationary",
    "n_cargo_tanker_anchored",  # status 1 only; ships moored at a berth (status 5) are not included
]

# Columns in table order, matching schema.sql (fact_key is generated by Postgres).
TABLE_COLUMNS = {
    "dim_parameter": ["parameter_key", "param", "description"],
    "dim_station": ["station_key", "site_id", "county", "lat", "lon", "distance_km", "wx_station"],
    "dim_time": [
        "time_key",
        "ts_utc",
        "date_utc",
        "year",
        "month",
        "day",
        "hour_utc",
        "ts_local",
        "date_local",
        "hour_local",
        "dow_local",
        "is_weekend_local",
    ],
    "dim_smoke": ["date_key", "date_local", "smoke_density", "smoke_polygons", "file_found"],
    "dim_weather": [
        "weather_key",
        "wx_station",
        "time_key",
        "temperature",
        "dew_point_temperature",
        "relative_humidity",
        "wind_speed",
        "wind_gust",
        "wind_direction",
        "wind_u",
        "wind_v",
        "station_level_pressure",
        "precipitation",
        "visibility",
        "n_obs",
    ],
    "dim_vessel_activity": ["vessel_key", "station_key", "time_key", "radius_km", "n_cells"]
    + COUNT_COLS
    + ["mean_sog", "mean_sog_underway"],
    "dim_bay_activity": ["time_key"] + COUNT_COLS + ["mean_sog", "mean_sog_underway", "low_coverage"],
    "fact_air_quality": [
        "time_key",
        "station_key",
        "parameter_key",
        "weather_key",
        "smoke_key",
        "vessel_key",
        "value",
        "units",
        "n_poc",
    ],
}
LOAD_ORDER = list(TABLE_COLUMNS)


# --------------------------------------------------------------------------- helpers
def col(df: pd.DataFrame, name: str) -> pd.Series:
    """Column if present, else all-NaN, so a missing optional column does not crash the build."""
    return df[name] if name in df.columns else pd.Series(np.nan, index=df.index)


def to_utc_hour(s: pd.Series) -> pd.Series:
    return pd.to_datetime(s, utc=True).dt.floor("h")


def time_key(hour_utc: pd.Series) -> pd.Series:
    return hour_utc.dt.strftime("%Y%m%d%H").astype("int64")


def date_key(dates: pd.Series) -> pd.Series:
    return pd.to_datetime(dates).dt.strftime("%Y%m%d").astype("int64")


def haversine_km(lat1, lon1, lat2, lon2):
    r = 6371.0088
    p1, p2 = np.radians(lat1), np.radians(lat2)
    dphi = p2 - p1
    dlmb = np.radians(np.asarray(lon2) - lon1)
    a = np.sin(dphi / 2) ** 2 + np.cos(p1) * np.cos(p2) * np.sin(dlmb / 2) ** 2
    return 2 * r * np.arcsin(np.sqrt(a))


# --------------------------------------------------------------------------- dimensions
def build_dim_parameter() -> pd.DataFrame:
    return pd.DataFrame([{"parameter_key": k, "param": p, "description": d} for p, (k, d) in PARAMS.items()])


def classify_wx(station_values) -> dict[str, str]:
    """Map raw GHCN station folder values to LGB / LAX. Raises if none match."""
    out = {}
    for raw in pd.Series(list(station_values)).dropna().astype(str).unique():
        for label, spec in WX_STATIONS.items():
            if any(tok in raw.lower() for tok in spec["tokens"]):
                out[raw] = label
    if not out:
        seen = sorted(pd.Series(list(station_values)).dropna().astype(str).unique())
        raise ValueError(
            f"No GHCN station matched {list(WX_STATIONS)}; saw {seen}. Edit WX_STATIONS tokens in warehouse/build.py."
        )
    return out


def build_dim_station(epa: pd.DataFrame, wx_labels: set[str]) -> pd.DataFrame:
    e = epa[epa["param"].isin(PARAMS)]
    st = (
        e.groupby("site_id", as_index=False)
        .agg(
            county=("county", "first"),
            lat=("lat", "first"),
            lon=("lon", "first"),
            distance_km=("distance_km", "first"),
        )
        .sort_values("site_id")
        .reset_index(drop=True)
    )
    st.insert(0, "station_key", np.arange(1, len(st) + 1))

    def nearest(row):
        cands = {
            lab: haversine_km(row.lat, row.lon, spec["lat"], spec["lon"])
            for lab, spec in WX_STATIONS.items()
            if lab in wx_labels
        }
        return min(cands, key=cands.get) if cands else None

    st["wx_station"] = st.apply(nearest, axis=1)
    return st


def build_dim_weather(ghcnh: pd.DataFrame, label_map: dict[str, str]) -> pd.DataFrame:
    df = ghcnh.copy()
    df["wx_station"] = df["station"].astype(str).map(label_map)
    df = df.dropna(subset=["wx_station"])
    df["hour_utc"] = to_utc_hour(df["ts_utc"])

    speed, direc = col(df, "wind_speed"), col(df, "wind_direction")
    rad = np.deg2rad(direc)
    # East-west and north-south components. Calm/variable wind has a null direction in the lake
    # (the source's 999 is stored as null): it adds nothing to the direction average.
    df["wind_u"] = -speed * np.sin(rad)
    df["wind_v"] = -speed * np.cos(rad)

    g = df.groupby(["wx_station", "hour_utc"], as_index=False).agg(
        temperature=("temperature", "mean"),
        dew_point_temperature=("dew_point_temperature", "mean"),
        relative_humidity=("relative_humidity", "mean"),
        wind_speed=("wind_speed", "mean"),
        wind_gust=("wind_gust", "max"),
        wind_u=("wind_u", "mean"),
        wind_v=("wind_v", "mean"),
        station_level_pressure=("station_level_pressure", "mean"),
        precipitation=("precipitation", lambda s: s.sum(min_count=1)),  # CHECK units/accumulation
        visibility=("visibility", "mean"),
        n_obs=("ts_utc", "size"),
    )
    # Average direction as a vector so 350 and 10 degrees give about 0, not 180.
    g["wind_direction"] = (np.degrees(np.arctan2(-g["wind_u"], -g["wind_v"])) % 360).where(
        np.hypot(g["wind_u"], g["wind_v"]) > 1e-9  # no usable bearing (all calm/variable) -> NULL
    )
    g["time_key"] = time_key(g["hour_utc"])
    g = g.sort_values(["wx_station", "time_key"]).reset_index(drop=True)
    g.insert(0, "weather_key", np.arange(1, len(g) + 1))
    return g


def build_dim_smoke(hms: pd.DataFrame) -> pd.DataFrame:
    s = hms.copy()
    s["date_local"] = pd.to_datetime(s["date"]).dt.date
    found = col(s, "file_found").fillna(False).astype(bool)
    # No HMS file for the day means "unknown", not "no smoke".
    # Nullable ints so COPY writes 2, not 2.0 (Postgres rejects "2.0" for SMALLINT/INTEGER).
    s["smoke_density"] = pd.to_numeric(col(s, "smoke_density")).where(found).astype("Int64")
    s["smoke_polygons"] = pd.to_numeric(col(s, "smoke_polygons")).where(found).astype("Int64")
    s["file_found"] = found
    s["date_key"] = date_key(s["date_local"])
    s = s.drop_duplicates("date_key", keep="last").sort_values("date_key")
    return s[TABLE_COLUMNS["dim_smoke"]].reset_index(drop=True)


def build_dim_vessel(vessels: pd.DataFrame, stations: pd.DataFrame, radius_km: float = RADIUS_KM) -> pd.DataFrame:
    """Vessel activity within radius_km of each monitor, per UTC hour.

    n_vessels is summed over cells, so a ship that crosses two cells in one hour is counted
    twice: treat it as an activity index, not an exact headcount. Hours with no row mean no
    pings were recorded nearby (no ships, or no AIS coverage); the modeling view fills zeros.
    """
    cols = ["vessel_key", "station_key", "time_key", "radius_km", "n_cells"] + COUNT_COLS
    cols += ["mean_sog", "mean_sog_underway"]
    if vessels.empty or stations.empty:
        return pd.DataFrame(columns=cols)

    cells = vessels[["cell_lat", "cell_lon"]].drop_duplicates()
    clat = cells["cell_lat"].to_numpy() + CELL_DEG / 2
    clon = cells["cell_lon"].to_numpy() + CELL_DEG / 2
    pairs = []
    for st in stations.itertuples():
        near = haversine_km(st.lat, st.lon, clat, clon) <= radius_km
        pairs.append(cells[near].assign(station_key=st.station_key))
    pairs = pd.concat(pairs)
    if pairs.empty:
        return pd.DataFrame(columns=cols)

    j = vessels.merge(pairs, on=["cell_lat", "cell_lon"])
    j["hour_utc"] = to_utc_hour(j["hour_utc"])
    for c in COUNT_COLS:
        j[c] = pd.to_numeric(col(j, c)).fillna(0)
    sog = pd.to_numeric(col(j, "mean_sog"))
    sogu = pd.to_numeric(col(j, "mean_sog_underway"))
    j["_sog_w"] = (sog * j["n_pings"]).where(sog.notna(), 0.0)
    j["_sog_n"] = j["n_pings"].where(sog.notna(), 0.0)
    j["_sogu_w"] = (sogu * j["n_underway"]).where(sogu.notna(), 0.0)
    j["_sogu_n"] = j["n_underway"].where(sogu.notna(), 0.0)

    agg = {c: (c, "sum") for c in COUNT_COLS}
    agg.update(
        n_cells=("cell_lat", "size"),
        _sog_w=("_sog_w", "sum"),
        _sog_n=("_sog_n", "sum"),
        _sogu_w=("_sogu_w", "sum"),
        _sogu_n=("_sogu_n", "sum"),
    )
    g = j.groupby(["station_key", "hour_utc"], as_index=False).agg(**agg)
    for c in COUNT_COLS + ["n_cells"]:
        g[c] = g[c].round().astype("int64")  # INTEGER columns: write 4, not 4.0
    g["mean_sog"] = (g["_sog_w"] / g["_sog_n"]).where(g["_sog_n"] > 0)
    g["mean_sog_underway"] = (g["_sogu_w"] / g["_sogu_n"]).where(g["_sogu_n"] > 0)
    g["radius_km"] = radius_km
    g["time_key"] = time_key(g["hour_utc"])
    g = g.sort_values(["station_key", "time_key"]).reset_index(drop=True)
    g.insert(0, "vessel_key", np.arange(1, len(g) + 1))
    return g


def build_dim_bay(bay: pd.DataFrame) -> pd.DataFrame:
    """Bay-wide vessel activity, one row per UTC hour (features/bay_hourly).

    Each vessel is counted once per hour, so unlike the per-monitor table these are real
    (approximate) headcounts. low_coverage marks hours with too few AIS pings to trust: those
    are AIS outages, not empty water, so filter on it before using the counts.
    """
    cols = ["time_key"] + COUNT_COLS + ["mean_sog", "mean_sog_underway", "low_coverage"]
    if bay is None or bay.empty:
        return pd.DataFrame(columns=cols + ["hour_utc"])
    g = bay.copy()
    g["hour_utc"] = to_utc_hour(g["hour_utc"])
    for c in COUNT_COLS:
        g[c] = pd.to_numeric(col(g, c)).fillna(0).round().astype("int64")
    g["mean_sog"] = pd.to_numeric(col(g, "mean_sog"))
    g["mean_sog_underway"] = pd.to_numeric(col(g, "mean_sog_underway"))
    g["low_coverage"] = col(g, "low_coverage").astype("boolean")
    g["time_key"] = time_key(g["hour_utc"])
    return g.drop_duplicates("time_key").sort_values("time_key").reset_index(drop=True)[cols + ["hour_utc"]]


def build_dim_time(hours: pd.Series) -> pd.DataFrame:
    h = pd.Series(pd.to_datetime(hours, utc=True).dt.floor("h").unique()).sort_values()
    h = h.reset_index(drop=True)
    local = h.dt.tz_convert(LOCAL_TZ)
    t = pd.DataFrame(
        {
            "time_key": time_key(h),
            "ts_utc": h,
            "date_utc": h.dt.date,
            "year": h.dt.year,
            "month": h.dt.month,
            "day": h.dt.day,
            "hour_utc": h.dt.hour,
            "ts_local": local.dt.tz_localize(None),  # local wall-clock time
            "date_local": local.dt.date,
            "hour_local": local.dt.hour,
            "dow_local": local.dt.day_of_week,  # Monday = 0
        }
    )
    t["is_weekend_local"] = t["dow_local"] >= 5
    return t


# --------------------------------------------------------------------------- fact
def build_fact(
    epa: pd.DataFrame,
    stations: pd.DataFrame,
    weather: pd.DataFrame,
    smoke: pd.DataFrame,
    vessels: pd.DataFrame,
) -> pd.DataFrame:
    e = epa[epa["param"].isin(PARAMS)].copy()
    e["hour_utc"] = to_utc_hour(e["ts_utc"])
    f = e.groupby(["site_id", "param", "hour_utc"], as_index=False).agg(
        value=("value", "mean"), units=("units", "first"), n_poc=("poc", "nunique")
    )
    f = f.merge(stations[["site_id", "station_key", "wx_station"]], on="site_id", how="inner")
    f["parameter_key"] = f["param"].map(lambda p: PARAMS[p][0])
    f["time_key"] = time_key(f["hour_utc"])
    f["date_key_local"] = date_key(f["hour_utc"].dt.tz_convert(LOCAL_TZ).dt.date)

    f = f.merge(weather[["wx_station", "time_key", "weather_key"]], how="left", on=["wx_station", "time_key"])
    f = f.merge(vessels[["station_key", "time_key", "vessel_key"]], how="left", on=["station_key", "time_key"])
    known = set(smoke["date_key"])
    f["smoke_key"] = f["date_key_local"].where(f["date_key_local"].isin(known))

    for c in ["weather_key", "smoke_key", "vessel_key"]:
        f[c] = f[c].astype("Int64")
    f = f.sort_values(["time_key", "station_key", "parameter_key"]).reset_index(drop=True)
    return f


def build_all(tables: dict[str, pd.DataFrame]) -> dict[str, pd.DataFrame]:
    """tables: epa, ghcnh, hms, vessels (raw lake tables as DataFrames) -> warehouse tables."""
    label_map = classify_wx(tables["ghcnh"]["station"])
    stations = build_dim_station(tables["epa"], set(label_map.values()))
    weather = build_dim_weather(tables["ghcnh"], label_map)
    smoke = build_dim_smoke(tables["hms"])
    vessels = build_dim_vessel(tables["vessels"], stations)
    bay = build_dim_bay(tables.get("bay"))
    fact = build_fact(tables["epa"], stations, weather, smoke, vessels)

    hours = pd.concat(
        [
            fact["hour_utc"],
            weather["hour_utc"],
            pd.to_datetime(vessels["hour_utc"], utc=True) if len(vessels) else pd.Series(dtype="datetime64[ns, UTC]"),
            pd.to_datetime(bay["hour_utc"], utc=True) if len(bay) else pd.Series(dtype="datetime64[ns, UTC]"),
        ]
    )
    return {
        "dim_parameter": build_dim_parameter(),
        "dim_station": stations,
        "dim_time": build_dim_time(hours),
        "dim_smoke": smoke,
        "dim_weather": weather,
        "dim_vessel_activity": vessels,
        "dim_bay_activity": bay,
        "fact_air_quality": fact,
    }


# --------------------------------------------------------------------------- IO
def read_table(lake: str | Path, rel: str) -> pd.DataFrame:
    """Read a hive-partitioned Parquet table from the lake (needs pyarrow)."""
    import pyarrow.dataset as ds

    path = Path(lake) / rel
    return ds.dataset(path, format="parquet", partitioning="hive").to_table().to_pandas()


def read_lake(lake: str | Path) -> dict[str, pd.DataFrame]:
    bay_path = Path(lake) / "features/bay_hourly"
    return {
        "bay": read_table(lake, "features/bay_hourly") if bay_path.exists() else pd.DataFrame(),
        "epa": read_table(lake, "raw/epa_hourly"),
        "ghcnh": read_table(lake, "raw/ghcnh"),
        "hms": read_table(lake, "raw/hms_smoke"),
        "vessels": read_table(lake, "features/vessel_hourly"),
    }


def default_dsn() -> str:
    if os.environ.get("WAREHOUSE_DSN"):
        return os.environ["WAREHOUSE_DSN"]
    user = os.environ.get("WAREHOUSE_USER", "harbor")
    pw = os.environ.get("WAREHOUSE_PASSWORD", "harbor")
    host = os.environ.get("WAREHOUSE_HOST", "localhost")
    port = os.environ.get("WAREHOUSE_PORT", "5432")
    db = os.environ.get("WAREHOUSE_DB", "harbor_haze")
    return f"postgresql://{user}:{pw}@{host}:{port}/{db}"


def load_postgres(frames: dict[str, pd.DataFrame], dsn: str) -> None:
    """Recreate the schema, then COPY every table in dependency order, in one transaction."""
    import psycopg

    here = Path(__file__).parent
    with psycopg.connect(dsn) as conn:
        with conn.cursor() as cur:
            cur.execute((here / "schema.sql").read_text())
            for name in LOAD_ORDER:
                cols = TABLE_COLUMNS[name]
                buf = io.StringIO()
                frames[name][cols].to_csv(buf, index=False, header=False, na_rep="")
                buf.seek(0)
                with cur.copy(f"COPY {name} ({', '.join(cols)}) FROM STDIN WITH (FORMAT csv, NULL '')") as cp:
                    cp.write(buf.read())
                print(f"loaded {name}: {len(frames[name]):,} rows")
            cur.execute((here / "views.sql").read_text())
        conn.commit()


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--lake", default="data/lake")
    ap.add_argument("--dsn", default=None, help="default: WAREHOUSE_DSN or WAREHOUSE_* env vars")
    ap.add_argument("--dry-run", metavar="DIR", help="write CSVs here instead of loading Postgres")
    args = ap.parse_args()

    frames = build_all(read_lake(args.lake))
    if args.dry_run:
        out = Path(args.dry_run)
        out.mkdir(parents=True, exist_ok=True)
        for name, df in frames.items():
            df[TABLE_COLUMNS[name]].to_csv(out / f"{name}.csv", index=False)
            print(f"wrote {name}: {len(df):,} rows")
        return
    load_postgres(frames, args.dsn or default_dsn())


if __name__ == "__main__":
    main()
